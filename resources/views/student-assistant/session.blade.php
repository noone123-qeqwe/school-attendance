    <div class="tch-card-head"><div class="tch-card-title"><i class="bi bi-qr-code me-2"></i> Student Assistant</div></div>
    <div style="padding:24px;">
        <h1 style="font-size:1.4rem;color:#f3e7cd;">{{ $session->subject?->name }}</h1>
        <p style="color:#b39b82;">{{ $session->subject?->section }} · Session ends {{ $session->session_ends_at->format('h:i A') }}</p>
        <div id="assistantQrMessage" role="status" aria-live="polite" style="color:#b39b82;margin-bottom:16px;">Connecting to attendance session...</div>
        <div id="assistantQrCanvas" aria-label="Current attendance QR code" style="display:none;width:max-content;max-width:100%;background:#fff;padding:14px;border-radius:14px;margin:0 auto 16px;"></div>
        <div class="d-flex justify-content-between flex-wrap gap-2" style="color:#b39b82;">
            <span>QR Status: <strong id="assistantQrStatus" style="color:#f3e7cd;">Checking</strong></span>
            <span>Refreshes in: <strong id="assistantQrCountdown" style="color:#f3e7cd;">--:--</strong></span>
        </div>
        <p style="color:#b39b82;margin-top:12px;">Generated by: <span id="assistantQrGenerator">—</span></p>
        <button id="assistantQrReplace" type="button" class="tch-btn tch-btn-primary">Generate New QR</button>
